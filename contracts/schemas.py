"""Shared JSON Schema contracts for TERRA-SAFE X.
Version: 1.1.0
Authoritative specification for Frontend (React/TS), Backend (FastAPI), AI Service, SAGE AI, and Simulator.
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class RobotMode(str, Enum):
    MANUAL = "MANUAL"
    AUTONOMOUS = "AUTONOMOUS"
    EMERGENCY_STOP = "EMERGENCY_STOP"
    SIMULATION = "SIMULATION"


class ConnectionState(str, Enum):
    CONNECTED = "CONNECTED"
    DISCONNECTED = "DISCONNECTED"
    SIMULATED = "SIMULATED"
    DEGRADED = "DEGRADED"


class AlertLevel(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class RiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"
    UNKNOWN = "UNKNOWN"


class GuidanceAction(str, Enum):
    INVESTIGATE = "INVESTIGATE"
    OBSERVE = "OBSERVE"
    SLOW_DOWN = "SLOW_DOWN"
    STOP = "STOP"
    DATA_UNAVAILABLE = "DATA_UNAVAILABLE"


class CommandExecutionState(str, Enum):
    RECEIVED = "RECEIVED"
    ACCEPTED = "ACCEPTED"
    SIMULATED_EXECUTION = "SIMULATED_EXECUTION"
    COMPLETED = "COMPLETED"
    REJECTED = "REJECTED"
    FAILED = "FAILED"


class SensorReadings(BaseModel):
    """Raw & conditioned sensor telemetry from ESP32 or Simulator."""
    temperature_c: float = Field(..., description="Temperature in Celsius (e.g. DHT22 / BME280)")
    humidity_pct: float = Field(..., description="Relative humidity %")
    distance_cm: float = Field(..., description="Forward obstacle distance via HC-SR04 ultrasonic")
    gas_mq2_raw: int = Field(..., description="MQ-2 smoke & combustible gas ADC raw reading (0-4095)")
    flame_detected: bool = Field(..., description="IR Flame sensor digital output (True if flame detected)")
    motion_pir: bool = Field(..., description="Passive IR motion detector (True if motion detected)")
    imu_roll_deg: float = Field(..., description="MPU6050 Roll angle in degrees")
    imu_pitch_deg: float = Field(..., description="MPU6050 Pitch angle in degrees")
    imu_yaw_deg: float = Field(..., description="MPU6050 Heading/Yaw angle in degrees")
    battery_pct: int = Field(..., ge=0, le=100, description="Battery state of charge %")
    battery_volts: float = Field(..., description="Pack voltage (e.g., 11.1V - 12.6V 3S LiPo)")
    wifi_rssi_dbm: int = Field(..., description="Wi-Fi signal strength in dBm")
    lora_rssi_dbm: Optional[int] = Field(None, description="Optional LoRa backup RSSI in dBm")
    sensor_validity: Dict[str, bool] = Field(
        default_factory=lambda: {
            "temperature": True,
            "humidity": True,
            "distance": True,
            "gas": True,
            "flame": True,
            "motion": True,
            "imu": True,
            "battery": True
        },
        description="Integrity status of individual sensors"
    )


class AIDetection(BaseModel):
    """Object detection from AI vision model or SAGE reasoning."""
    detection_id: str
    label: str = Field(..., description="Detected object: person, fire, smoke, rubble_hazard")
    confidence: float = Field(..., ge=0.0, le=1.0)
    bounding_box: List[float] = Field(..., description="Normalized coords [x_min, y_min, x_max, y_max]")
    evidence_frames: int = Field(1, description="Number of consecutive frames observed")
    status: str = Field("UNVERIFIED", description="UNVERIFIED, CONFIRMED, or REPEATED")
    timestamp: str
    source_provenance: str = Field("SIMULATION", description="SAMPLE_IMAGE, SIMULATION, or HARDWARE")


class SAGERecommendation(BaseModel):
    """Structured tactical guidance generated by the Sensor-Aware Guidance Engine."""
    action: GuidanceAction
    summary: str
    reason: str
    evidence_references: List[str] = Field(default_factory=list)
    timestamp: str
    confidence: float = Field(..., ge=0.0, le=1.0)
    uncertainty: float = Field(0.0, ge=0.0, le=1.0)
    requires_operator_approval: bool = True
    proposed_observation: Optional[str] = None
    source_provenance: str = Field("SAGE_RULE_ENGINE", description="SAGE_RULE_ENGINE or FALLBACK")


class RiskAssessment(BaseModel):
    """Explainable risk computation derived from multi-sensor + AI inputs."""
    overall_score: int = Field(..., ge=0, le=100, description="0-100 hazard risk score")
    risk_level: RiskLevel
    contributors: Dict[str, float] = Field(
        ...,
        description="Key-value mapping of contributors (e.g., fire_hazard: 0.35, toxic_gas: 0.25)"
    )
    primary_hazards: List[str] = Field(default_factory=list)
    missing_evidence: List[str] = Field(default_factory=list)
    uncertainty: float = Field(0.0, ge=0.0, le=1.0)
    recommendation: str = Field(..., description="Prescriptive advice string for backward compatibility")
    sage_guidance: Optional[SAGERecommendation] = None


class RobotTelemetry(BaseModel):
    """Full live telemetry payload broadcast over WebSocket with sequencing and freshness."""
    timestamp: str
    sequence_number: int = Field(0, description="Monotonically increasing sequence number")
    robot_id: str = "TERRA-01"
    is_simulation: bool = True
    source_provenance: str = Field("SIMULATION", description="SIMULATION, SAMPLE_IMAGE, or HARDWARE")
    robot_ip: str = "192.168.1.45 (Simulated)"
    cam_ip: str = "192.168.1.46 (Simulated)"
    mode: RobotMode = RobotMode.SIMULATION
    connection: ConnectionState = ConnectionState.SIMULATED
    data_freshness_ms: int = Field(0, description="Age of latest telemetry payload in ms")
    sensors: SensorReadings
    recent_detections: List[AIDetection] = Field(default_factory=list)
    risk_assessment: RiskAssessment
    motor_safety_locked: bool = Field(
        True,
        description="Physical motors locked by default until verified hardware operator unlocks"
    )
    position: Dict[str, float] = Field(
        default_factory=lambda: {"x": 5.2, "y": 3.8, "heading_deg": 184.0}
    )


class MotorCommand(BaseModel):
    """Command payload for operator navigation and gimbal control."""
    command_id: Optional[str] = Field(None, description="UUID or unique client identifier for idempotency")
    command: str = Field(..., description="FORWARD, BACKWARD, LEFT, RIGHT, STOP, PAN_LEFT, PAN_RIGHT, TILT_UP, TILT_DOWN, MISSION_START, MISSION_PAUSE")
    speed_pct: int = Field(default=30, ge=0, le=100)
    override_safety: bool = Field(
        False,
        description="Explicit flag required to dispatch to physical GPIO/hardware; ignored in simulation"
    )
    timestamp: Optional[str] = None


class CommandAcknowledgement(BaseModel):
    """Formal bidirectional acknowledgement for operator commands."""
    command_id: str
    command: str
    status: CommandExecutionState
    accepted: bool
    reason: str
    timestamp: str
    speed_pct: int = 30
    override_active: bool = False
    is_simulation: bool = True


class MissionEvent(BaseModel):
    event_id: str
    timestamp: str
    level: AlertLevel
    category: str = Field(..., description="AI_DETECTION, SENSOR_ALERT, NAVIGATION, SYSTEM, SAGE_TACTICAL")
    title: str
    detail: str
    source_provenance: str = Field("SIMULATION", description="SIMULATION, SAMPLE_IMAGE, or HARDWARE")
    acknowledged: bool = False


class SimulationScenarioConfig(BaseModel):
    scenario_name: str = Field("NORMAL", description="NORMAL, OBSTACLE_PROXIMITY, GAS_ALERT, TEMP_ALERT, LOW_BATTERY, COMM_LOSS, INVALID_SENSOR, STALE_TELEMETRY, CAMERA_FAILURE")
    fault_active: bool = False
    custom_params: Dict[str, Any] = Field(default_factory=dict)


class SystemHealth(BaseModel):
    status: str = "HEALTHY"
    version: str = "1.1.0"
    is_simulation: bool = True
    active_connections: int = 0
    services: Dict[str, str] = Field(
        default_factory=lambda: {
            "fastapi_backend": "UP",
            "ai_vision_module": "READY (LIGHTWEIGHT)",
            "sage_engine": "ACTIVE (RULE-BASED EXPLAINABLE)",
            "telemetry_stream": "ACTIVE",
            "esp32_firmware_bridge": "MOCK_SIMULATION_MODE",
            "motor_safety_interlock": "LOCKED (SAFETY SECURED)"
        }
    )
